import { prisma } from '../src/lib/prisma';

async function main() {
  const blog = await prisma.blogPost.findFirst({
    where: { title: { contains: "Medical Tourism in India" } }
  });

  if (!blog) {
    console.log("Blog not found");
    return;
  }

  const translations = {
    ar: {
      title: "السياحة العلاجية في الهند: دليل شامل للمرضى الدوليين",
      excerpt: "يُعد قطاع السياحة العلاجية في الهند من بين أسرع القطاعات نموًا، حيث يجذب المرضى من جميع أنحاء العالم. يهدف هذا الدليل الشامل إلى مساعدتك في فهم العملية.",
      content: `
لماذا يختار المرضى الدوليون الهند؟

من أهم عوامل الجذب في الهند توافر مجموعة واسعة من الخبرات الطبية في جميع مراكز الرعاية الصحية الكبرى. يسافر المرضى الدوليون إلى الهند لتلقي العلاج في العديد من التخصصات، بما في ذلك رعاية القلب، والأورام، وجراحة العظام، وجراحة المخ والأعصاب، وزراعة الأعضاء، وعلاج الخصوبة، وإجراءات الأسنان، والخدمات المتخصصة الأخرى.

يمكن أن تكون التكلفة أيضًا اعتبارًا مهمًا. تختلف نفقات العلاج بشكل كبير اعتمادًا على المستشفى والطبيب والإجراء والحالة الطبية ومدة الإقامة والخدمات الإضافية المطلوبة. لذلك، يجب على المرضى الدوليين مقارنة تقديرات العلاج الكاملة بدلاً من اختيار مقدم الخدمة بناءً على سعر معلن فقط.

كما شهد قطاع السياحة العلاجية في الهند نموًا كبيرًا. وفقًا لوزارة السياحة الهندية، ارتفع عدد السياح الأجانب القادمين لأغراض طبية من حوالي 183 ألفًا في عام 2020 إلى 659 ألفًا في عام 2023، قبل أن يصل إلى 644 ألفًا في عام 2024.

ما هي عملية السياحة العلاجية في الهند؟

بالنسبة للمريض الدولي، تبدأ الرحلة عادةً بمشاركة السجلات الطبية وتقارير التشخيص مع مستشفى أو مقدم رعاية صحية. يمكن للأطباء بعد ذلك تقييم المعلومات المتاحة وتحديد ما إذا كانت الاستشارة الشخصية أو المزيد من الفحوصات مطلوبة.
      `
    }
  };

  await prisma.blogPost.update({
    where: { id: blog.id },
    data: {
      translations: translations as any
    }
  });

  console.log("Blog translated successfully");
}

main().catch(console.error).finally(() => prisma.$disconnect());
